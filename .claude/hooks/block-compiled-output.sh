#!/usr/bin/env bash
# PreToolUse guard: refuse Edit/Write on generated JS output.
# These are compiled from TS sources — see [[feedback_ts_only]] memory.
file=$(jq -r '.tool_input.file_path // empty')
[ -z "$file" ] && exit 0
file="${file//\\//}"

case "$file" in
  */extensions/*/out/*.js)
    jq -n '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:"This is compiled output (out/*.js) regenerated by tsc — manual edits get overwritten. Edit the TypeScript source in the matching src/ directory instead."}}'
    ;;
  */extensions/null-tools/lib/agents.js)
    jq -n '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:"lib/agents.js is compiled from src/webview/agents.ts. Edit that TypeScript source instead — manual edits to lib/agents.js get overwritten on rebuild."}}'
    ;;
esac
exit 0
